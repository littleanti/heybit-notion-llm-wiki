function docTypes() {
  return Object.keys(SECTIONS);
}

function sectionsFor(docType) {
  const list = SECTIONS[docType];
  if (!list) throw new Error(`알 수 없는 문서유형: ${docType} (허용: ${docTypes().join(', ')})`);
  return list.slice();
}

// 유형별 골격 본문. 내용은 비우고 안내만 남긴다 — Claude 가 Edit 로 채운다.
function skeleton(docType, { today, author } = {}) {
  const out = [];
  for (const name of sectionsFor(docType)) {
    out.push(`## ${name}`);
    if (name === '변경 이력') {
      out.push(`- ${today || '0000-00-00'} (${author || '작성자'}) 최초 작성`);
    } else {
      out.push(`<!-- ${HINTS[name] || '내용'} -->`);
    }
    out.push('');
  }
  return out.join('\n').trimEnd() + '\n';
}

module.exports = { SECTIONS, HINTS, docTypes, sectionsFor, skeleton };
